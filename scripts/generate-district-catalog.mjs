import { readFile, writeFile } from "node:fs/promises";

const source = new URL("../apps/web/public/data/warsaw-msi.geojson", import.meta.url);
const target = new URL("../apps/web/src/features/settings/districts.ts", import.meta.url);
const data = JSON.parse(await readFile(source, "utf8"));
const grouped = new Map();
for (const {
  properties: { district, name },
} of data.features) {
  if (!district || !name) throw new Error("MSI area without district or name");
  if (!grouped.has(district)) grouped.set(district, new Set());
  grouped.get(district).add(name);
}
if (grouped.size !== 18) throw new Error("Expected all 18 Warsaw districts");
const catalog = [...grouped]
  .sort(([a], [b]) => a.localeCompare(b, "pl"))
  .map(([district, names]) => ({
    district,
    subdistricts: [...names].sort((a, b) => a.localeCompare(b, "pl")),
  }));
await writeFile(
  target,
  `// Generated by scripts/generate-district-catalog.mjs from the statistics MSI dataset.\n// Source: OpenStreetMap contributors, ODbL; see docs/reference/warsaw-msi-boundaries.md.\nexport const warsawDreamDistrictCatalog = ${JSON.stringify(catalog, null, 2)} as const;\n`,
  "utf8",
);
console.log(
  `Generated ${catalog.length} districts and ${catalog.reduce((n, d) => n + d.subdistricts.length, 0)} MSI areas.`,
);
